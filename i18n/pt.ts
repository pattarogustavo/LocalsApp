// DeepStringify: replaces all string literal types with `string`, and function types with their signatures
type DeepStringify<T> = T extends string
  ? string
  : T extends (n: number) => string
  ? (n: number) => string
  : T extends (s: string) => string
  ? (s: string) => string
  : T extends object
  ? { [K in keyof T]: DeepStringify<T[K]> }
  : T;

